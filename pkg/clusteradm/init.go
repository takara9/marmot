package clusteradm

import (
	"context"
	"fmt"
	"io"
	"net"
	"os"
	"strings"
	"time"

	"github.com/takara9/marmot/api"
)

type InitOptions struct {
	EtcdIP            string
	UnderlayInterface string
	DryRun            bool
	// nil でなければ、変更の実行前に呼び出し、false なら何も変更せず中止する
	Confirm func(summary string) bool
}

func etcdURL(ip string) string {
	return fmt.Sprintf("http://%s:%d", ip, etcdClientPort)
}

func dropInContent(ip string) []byte {
	// etcd は環境変数とフラグの両方で同じ項目が指定されると起動を拒否する。
	// override.conf などで ETCD_LISTEN_CLIENT_URLS 等が設定されていても、
	// UnsetEnvironment は他の Environment=/EnvironmentFile= より後に評価され、ファイル名順に依存せず除去できる。
	return []byte(fmt.Sprintf(`# Generated by maadm cluster init
[Service]
Environment="DAEMON_ARGS=--listen-client-urls http://127.0.0.1:%[2]d,http://%[1]s:%[2]d --advertise-client-urls http://%[1]s:%[2]d"
UnsetEnvironment=%[3]s
`, ip, etcdClientPort, strings.Join(conflictingEtcdEnvNames, " ")))
}

// conflictingEtcdEnvNames は、drop-in で渡すフラグと競合する etcd の環境変数名。
var conflictingEtcdEnvNames = []string{"ETCD_LISTEN_CLIENT_URLS", "ETCD_ADVERTISE_CLIENT_URLS"}

// conflictingEtcdEnv は etcd.service に設定済みの、フラグと競合する環境変数を "NAME=value" で返す。
// 確認画面で利用者へ知らせるための情報であり、取得に失敗しても処理は止めない。
func conflictingEtcdEnv(env *Env) []string {
	if env.EtcdEnvironment == nil {
		return nil
	}
	out, err := env.EtcdEnvironment()
	if err != nil {
		return nil
	}
	var found []string
	for _, field := range strings.Fields(out) {
		field = strings.Trim(field, `"`)
		for _, name := range conflictingEtcdEnvNames {
			if strings.HasPrefix(field, name+"=") {
				found = append(found, field)
			}
		}
	}
	return found
}

func (e *Env) waitFor(ctx context.Context, what string, fn func() error) error {
	return e.waitForTimeout(ctx, e.WaitTimeout, what, fn)
}

func (e *Env) waitForTimeout(ctx context.Context, timeout time.Duration, what string, fn func() error) error {
	deadline := time.Now().Add(timeout)
	for {
		err := fn()
		if err == nil {
			return nil
		}
		if time.Now().After(deadline) {
			return fmt.Errorf("timeout waiting for %s: %w", what, err)
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-time.After(e.PollInterval):
		}
	}
}

func (e *Env) waitEtcd(ctx context.Context, urls ...string) error {
	for _, url := range urls {
		if err := e.waitFor(ctx, "etcd "+url, func() error { return e.EtcdHealth(ctx, url) }); err != nil {
			return err
		}
	}
	return nil
}

func (e *Env) waitUnitActive(ctx context.Context, unit string) error {
	return e.waitFor(ctx, unit, func() error {
		if !e.UnitActive(unit) {
			return fmt.Errorf("%s is not active", unit)
		}
		return nil
	})
}

// Init は、シングルノードの marmot をクラスタのコントロールノードへ変更する。
func Init(ctx context.Context, env *Env, opts InitOptions, out io.Writer) error {
	// 1. 事前チェック
	if !env.IsRoot() {
		return fmt.Errorf("root 権限で実行してください")
	}
	for _, unit := range []string{EtcdUnit, MarmotUnit} {
		if !env.UnitActive(unit) {
			return fmt.Errorf("%s が稼働していません", unit)
		}
	}
	cfg, err := readNodeConfig(env.ConfigPath)
	if err != nil {
		return err
	}
	if cfg.NodeName == "" {
		return fmt.Errorf("%s に node_name が設定されていません", env.ConfigPath)
	}

	currentURL := cfg.EtcdURL
	if currentURL == "" {
		currentURL = etcdURL("127.0.0.1")
	}
	store, err := env.OpenStore(currentURL)
	if err != nil {
		return fmt.Errorf("etcd (%s) へ接続できません: %w", currentURL, err)
	}
	info, err := store.GetClusterInfo()
	_ = store.Close()
	if err == nil {
		_, _ = fmt.Fprintf(out, "クラスタは既に有効です。変更しません。\nCLUSTER-ID: %s\n", info.ClusterId)
		return nil
	} else if !isNotFound(err) {
		return fmt.Errorf("クラスタ情報を取得できません: %w", err)
	}

	iface := opts.UnderlayInterface
	if iface == "" {
		iface = cfg.DefaultUnderlayInterface
	}
	if iface == "" {
		iface = DefaultUnderlayInterface
	}
	ifaceIP, err := env.InterfaceIPv4(iface)
	if err != nil {
		return err
	}
	etcdIP := opts.EtcdIP
	if etcdIP == "" {
		etcdIP = ifaceIP
	}
	if ip := net.ParseIP(etcdIP); ip == nil || ip.To4() == nil {
		return fmt.Errorf("--etcd-ip %q は IPv4 アドレスではありません", etcdIP)
	}
	newURL := etcdURL(etcdIP)

	summary := fmt.Sprintf(`以下の変更を行います。
  %s: DAEMON_ARGS で etcd を %s へ公開
  %s: etcd_url=%s, default_underlay_interface=%s
  etcd 内: クラスタ情報（CLUSTER-ID, マスター=%s）を保存
  %s と %s を再起動します（API が一時的に利用できなくなります。稼働中の VM は停止しません）
`, env.DropInPath, newURL, env.ConfigPath, newURL, iface, cfg.NodeName, EtcdUnit, MarmotUnit)
	if conflicts := conflictingEtcdEnv(env); len(conflicts) > 0 {
		summary += fmt.Sprintf(`注意: %s に次の環境変数が設定されています。
  %s
  etcd のフラグと競合して起動できなくなるため、drop-in の UnsetEnvironment で無効化します（待ち受けアドレスは上記の drop-in の指定に置き換わります）。
`, EtcdUnit, strings.Join(conflicts, "\n  "))
	}
	_, _ = fmt.Fprint(out, summary)

	if opts.DryRun {
		_, _ = fmt.Fprintln(out, "--dry-run が指定されたため、何も変更しません。")
		return nil
	}
	if opts.Confirm != nil && !opts.Confirm(summary) {
		return fmt.Errorf("中止しました")
	}

	// 以降は失敗したら、実行済みの変更を逆順に取り消して、元のシングルノード構成へ戻す
	var undos []func() error
	etcdTouched, marmotTouched := false, false
	rollback := func(cause error) error {
		_, _ = fmt.Fprintf(out, "エラー: %v\n元のシングルノード構成へ戻します。\n", cause)
		for i := len(undos) - 1; i >= 0; i-- {
			if err := undos[i](); err != nil {
				_, _ = fmt.Fprintf(out, "ロールバック失敗: %v\n", err)
			}
		}
		if etcdTouched {
			if err := env.Systemctl("daemon-reload"); err != nil {
				_, _ = fmt.Fprintf(out, "ロールバック失敗: %v\n", err)
			}
			if err := env.Systemctl("restart", EtcdUnit); err != nil {
				_, _ = fmt.Fprintf(out, "ロールバック失敗: %v\n", err)
			} else if err := env.waitEtcd(ctx, currentURL); err != nil {
				_, _ = fmt.Fprintf(out, "ロールバック失敗: %v\n", err)
			}
		}
		if marmotTouched {
			if err := env.Systemctl("restart", MarmotUnit); err != nil {
				_, _ = fmt.Fprintf(out, "ロールバック失敗: %v\n", err)
			}
		}
		return fmt.Errorf("cluster init に失敗しました（元の構成へ戻しました）: %w", cause)
	}

	// 2. etcd の外部公開（drop-in）
	dropIn, err := backupFile(env.DropInPath)
	if err != nil {
		return err
	}
	if err := writeFileAtomic(env.DropInPath, dropInContent(etcdIP), 0o644); err != nil {
		return rollback(fmt.Errorf("drop-in の書き込みに失敗: %w", err))
	}
	undos = append(undos, dropIn.restore)
	etcdTouched = true
	if err := env.Systemctl("daemon-reload"); err != nil {
		return rollback(err)
	}
	if err := env.Systemctl("restart", EtcdUnit); err != nil {
		return rollback(err)
	}
	if err := env.waitEtcd(ctx, newURL, etcdURL("127.0.0.1")); err != nil {
		return rollback(err)
	}

	// 3. marmotd.json の更新
	cfgBackup, err := backupFile(env.ConfigPath)
	if err != nil {
		return rollback(err)
	}
	data, err := os.ReadFile(env.ConfigPath)
	if err != nil {
		return rollback(err)
	}
	updated, err := updateJSONStrings(data, map[string]string{
		"etcd_url":                   newURL,
		"default_underlay_interface": iface,
	})
	if err != nil {
		return rollback(fmt.Errorf("%s の更新に失敗: %w", env.ConfigPath, err))
	}
	if err := writeFileAtomic(env.ConfigPath, updated, cfgBackup.mode); err != nil {
		return rollback(err)
	}
	undos = append(undos, cfgBackup.restore)
	marmotTouched = true

	// 4. クラスタ情報の保存
	clusterID := env.NewClusterID()
	now := env.Now()
	newStore, err := env.OpenStore(newURL)
	if err != nil {
		return rollback(fmt.Errorf("etcd (%s) へ接続できません: %w", newURL, err))
	}
	err = newStore.PutClusterInfo(api.ClusterInfo{ClusterId: clusterID, MasterNode: cfg.NodeName, CreationTimeStamp: &now})
	_ = newStore.Close()
	if err != nil {
		return rollback(fmt.Errorf("クラスタ情報の保存に失敗: %w", err))
	}
	undos = append(undos, func() error {
		s, err := env.OpenStore(newURL)
		if err != nil {
			return err
		}
		defer func() { _ = s.Close() }()
		return s.DeleteClusterInfo()
	})

	// 5. marmotd の再起動
	if err := env.Systemctl("restart", MarmotUnit); err != nil {
		return rollback(err)
	}
	if err := env.waitUnitActive(ctx, MarmotUnit); err != nil {
		return rollback(err)
	}

	// 6. 結果表示
	_, _ = fmt.Fprintf(out, "CLUSTER-ID: %s\netcd: %s\n他のノードで次のコマンドを実行してください:\n  maadm cluster join %s --master-node %s\n",
		clusterID, newURL, clusterID, etcdIP)
	return nil
}
